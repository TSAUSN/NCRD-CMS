// Documentation only: read a migrated disposable database, never apply SQL.
import { createRequire } from 'node:module'
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve, dirname } from 'node:path'
import { pathToFileURL } from 'node:url'
const root = resolve(import.meta.dirname, '..')
const { Client } = createRequire(join(root, 'packages/schema/package.json'))('pg')
const marker = 'Generated by scripts/current-sql.mjs'
export function referenceArea(name) {
  for (const [area, pattern] of [
    ['access', /(?:user|person|membership|permission|actor|session|auth|invite|super_admin)/],
    ['publishing', /(?:publish|release|schedule|readiness|review)/],
    ['media', /(?:media|upload|image|asset|document)/],
    ['frame', /(?:navigation|global_element|header|footer|site_shell)/],
    ['collections', /(?:collection|entry|reader|list)/],
    ['sites', /(?:site|chapter|division|domain|theme|font|redirect)/],
    ['editing', /(?:page|section|slot|recipe|canvas|preview|repeat)/],
    ['jobs', /(?:job|outbox|lease|cache|backup|retry|heartbeat)/],
  ])
    if (pattern.test(name)) return area
  return 'utilities'
}
export function withoutFunctionBodies(list) {
  return list
    .split('\n')
    .filter(line => !/^\d+;\s+\d+\s+\d+\s+FUNCTION\s+(?:app|public_api)\s/.test(line))
    .join('\n')
}
function command(program, args, env) {
  const r = spawnSync(program, args, { env, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  if (r.status !== 0) throw Error('Current SQL reference ' + program + ' failed; connection output omitted.')
  return r.stdout
}
export async function referenceFiles(connectionString) {
  const connection = new URL(connectionString)
  if (
    !['postgres:', 'postgresql:'].includes(connection.protocol) ||
    !['127.0.0.1', 'localhost'].includes(connection.hostname) ||
    connection.port !== '54329' ||
    !/^\/(?:cms_e2e_refactor|cms_test_template|cms_t_[a-z0-9_]+)$/.test(connection.pathname) ||
    connection.search ||
    connection.hash
  )
    throw Error('Current SQL reference only reads explicitly disposable local test databases on54329.')
  const env = {
    ...process.env,
    PGHOST: connection.hostname,
    PGPORT: connection.port,
    PGDATABASE: connection.pathname.slice(1),
    PGUSER: decodeURIComponent(connection.username),
    PGPASSWORD: decodeURIComponent(connection.password),
  }
  const db = new Client({ connectionString })
  await db.connect()
  const temp = mkdtempSync(join(tmpdir(), 'cms-current-sql-'))
  try {
    await db.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY')
    const snapshot = (await db.query('SELECT pg_export_snapshot() AS value')).rows[0].value
    const functions = (
      await db.query(
        "SELECT n.nspname AS schema,p.proname AS name,pg_get_function_identity_arguments(p.oid) AS arguments,pg_get_functiondef(p.oid) AS definition,pg_get_userbyid(p.proowner) AS owner,p.proacl::text AS acl FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname IN ('app','public_api') ORDER BY n.nspname,p.proname,pg_get_function_identity_arguments(p.oid)",
      )
    ).rows
    const migrations = (await db.query('SELECT name,checksum FROM cms_migrations ORDER BY name')).rows
    command(
      'pg_dump',
      ['--schema-only', '--format=custom', '--snapshot=' + snapshot, '--file=' + join(temp, 'schema.dump')],
      env,
    )
    const toc = command('pg_restore', ['--list', join(temp, 'schema.dump')], env)
    writeFileSync(join(temp, 'catalog.list'), withoutFunctionBodies(toc))
    const catalog = command(
      'pg_restore',
      ['--schema-only', '--file=-', '--use-list=' + join(temp, 'catalog.list'), join(temp, 'schema.dump')],
      env,
    )
      .replace(/^\\(?:un)?restrict .*\n/gm, '')
      .replace(/^-- Dumped (?:from database|by pg_dump) version .*\n/gm, '')
    await db.query('COMMIT')
    const files = new Map([
      [
        'catalog.sql',
        '-- ' + marker + '; documentation only. Function bodies are in their individual files.\n' + catalog,
      ],
      ['migrations.json', JSON.stringify({ generator: marker, migrations }, null, 2) + '\n'],
    ])
    const counts = new Map()
    for (const f of functions) counts.set(f.schema + '.' + f.name, (counts.get(f.schema + '.' + f.name) ?? 0) + 1)
    const index = []
    for (const f of functions) {
      if (!/^[a-z_][a-z0-9_]*$/.test(f.name)) throw Error('Unexpected SQL function identifier.')
      const signature = `${f.schema}.${f.name}(${f.arguments})`
      const suffix =
        counts.get(f.schema + '.' + f.name) > 1
          ? '__' + createHash('sha256').update(signature).digest('hex').slice(0, 8)
          : ''
      const file = `${f.schema}/${referenceArea(f.name)}/${f.name}${suffix}.sql`
      files.set(
        file,
        `-- ${marker}; documentation only.\n-- Signature: ${signature}\n-- Owner: ${f.owner}\n-- ACL: ${f.acl ?? '(default)'}\n\n${f.definition}`,
      )
      index.push(`| \`${signature}\` | [${f.schema}/${referenceArea(f.name)}](${file}) |`)
    }
    files.set(
      'README.md',
      `# Current database reference\n\n${marker}. Do not edit or apply these files.\n\nThis is one current definition for each of the ${functions.length} application functions,\nread with \`pg_get_functiondef\` after ${migrations.length} immutable migrations. Each file records\nits owner and ACL. [catalog.sql](catalog.sql) contains schemas, types, tables,\nconstraints, indexes, RLS policies and grants; function bodies are linked below.\nIt is a reading reference, not a replacement installer or a migration.\n\nTo change behavior, add an immutable migration and real-role database tests.\nRegenerate from a freshly migrated disposable database with:\n\n\`\`\`bash\nCURRENT_SQL_DATABASE_URL=postgres://cms:cms@127.0.0.1:54329/cms_e2e_refactor pnpm schema:reference\npnpm test:db\n\`\`\`\n\n\`pnpm schema:reference:check\` refuses stale/missing/extra generated files; the\ndatabase suite checks the reference against a fresh migrated clone. Dump client\nversion comments and random transport guards are omitted from this documentation.\nThe independent golden schema retains every SQL byte and owner/grant/policy.\nNumbered migrations remain the only runtime authority.\n\n| Function | Area and definition |\n| --- | --- |\n${index.join('\n')}\n`,
    )
    return files
  } finally {
    await db.end()
    rmSync(temp, { recursive: true, force: true })
  }
}
function existingFiles(directory, prefix = '') {
  if (!existsSync(directory)) return []
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry =>
    entry.isDirectory() ? existingFiles(join(directory, entry.name), prefix + entry.name + '/') : [prefix + entry.name],
  )
}
export function staleReference(files, directory) {
  return [...new Set([...files.keys(), ...existingFiles(directory)])]
    .sort()
    .filter(
      file =>
        !files.has(file) ||
        !existsSync(join(directory, file)) ||
        readFileSync(join(directory, file), 'utf8') !== files.get(file),
    )
}
async function main() {
  const files = await referenceFiles(process.env.CURRENT_SQL_DATABASE_URL ?? '')
  const out = join(root, 'packages/schema/current')
  const stale = staleReference(files, out)
  if (process.argv.includes('--check')) {
    if (stale.length) throw Error('Current SQL reference is stale: ' + stale.slice(0, 8).join(', '))
    console.log('Current SQL reference matches ' + files.size + ' generated files.')
    return
  }
  for (const old of existingFiles(out))
    if (!files.has(old)) {
      if (!readFileSync(join(out, old), 'utf8').includes(marker))
        throw Error('Refusing to remove a file not owned by the reference generator.')
      rmSync(join(out, old))
    }
  for (const [file, content] of files) {
    mkdirSync(dirname(join(out, file)), { recursive: true })
    writeFileSync(join(out, file), content)
  }
  console.log('Generated ' + files.size + ' current SQL reference files; no database change.')
}
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href)
  main().catch(error => {
    console.error(error.message)
    process.exitCode = 1
  })
