// Openly licensed, self-hosted fonts; copied at build time, never requested from a CDN.
for (const [packageName, files] of [
  [
    'open-sans',
    ['open-sans-latin-300-normal.woff2', 'open-sans-latin-400-normal.woff2', 'open-sans-latin-700-normal.woff2'],
  ],
  ['source-serif-4', ['source-serif-4-latin-400-normal.woff2', 'source-serif-4-latin-700-normal.woff2']],
  ['material-symbols-outlined', ['material-symbols-outlined-latin-400-normal.woff2']],
]) {
  const base = resolve(root, 'node_modules/@fontsource', packageName)
  const license = await readFile(resolve(base, 'LICENSE'))
  for (const app of ['admin', 'site']) {
    const output = resolve(root, `apps/${app}/public/cms-samples/fonts`)
    await mkdir(output, { recursive: true })
    await writeFile(resolve(output, `${packageName}-LICENSE.txt`), license)
    if (packageName === 'source-serif-4')
      await writeFile(
        resolve(output, 'source-serif-4-UPSTREAM-LICENSE.md'),
        await readFile(resolve(root, 'packages/seeds/licenses/source-serif-4-UPSTREAM-LICENSE.md')),
      )
    for (const file of files) await writeFile(resolve(output, file), await readFile(resolve(base, 'files', file)))
  }
}

