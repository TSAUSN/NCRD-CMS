const allowed = new Set(['.container', '.row', '.row>*', '.col-12', '.col-md-6', '.col-lg-4'])
const subset = postcss.root()
function copy(from, into) {
  for (const node of from.nodes ?? []) {
    if (node.type === 'rule') {
      const selectors = node.selectors.filter(selector => allowed.has(selector.trim()))
      if (selectors.length)
        into.append(node.clone({ selector: selectors.map(selector => '.core ' + selector).join(',') }))
    } else if (node.type === 'atrule' && node.name === 'media') {
      const next = node.clone({ nodes: [] })
      copy(node, next)
      if (next.nodes.length) into.append(next)
    }
  }
}
copy(original, subset)
