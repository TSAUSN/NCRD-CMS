import { expect, test } from '@playwright/test'
import { signIn } from './helpers.ts'

test('creates a governed header, retires it with cancel support, and restores its definition', async ({ page }) => {
  test.setTimeout(120_000)
  await signIn(page, 'root@example.test')
  await page.getByRole('main').getByRole('link', { name: 'Demo site', exact: true }).click()
  await expect(page).toHaveURL(/\/sites\/[0-9a-f-]+$/)
  const siteUrl = page.url()
  const name = `Frame lifecycle ${Date.now()}`
  await page.goto(`${siteUrl}/sections/new`)
  await page.getByRole('button', { name: 'HTML template', exact: true }).click()
  await page.getByLabel('What is this section called?', { exact: true }).fill(name)
  await page.locator('#sec-placement').selectOption('header')
  await page.getByLabel('HTML', { exact: true }).fill('<div><strong>{{heading}}</strong><nav>{{menu}}</nav></div>')
  await page.getByLabel('What menu holds', { exact: true }).selectOption('navigation')
  await page.getByRole('button', { name: 'Check and preview', exact: true }).click()
  await expect(page.frameLocator('iframe[title="Section preview"]').locator('header.cms-frame--header')).toBeVisible()
  await page.locator('#source-change-note').fill('Create a governed header for lifecycle checks')
  await page.getByRole('button', { name: 'Save this section', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Section saved', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Choose in Header & footer', exact: true })).toHaveAttribute(
    'href',
    `${new URL(siteUrl).pathname}/global-elements`,
  )
  await page.getByRole('button', { name: 'Create another', exact: true }).click()
  await expect(page.locator('#sec-placement')).toHaveValue('page')
  await expect(page.getByLabel('What is this section called?', { exact: true })).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Save this section', exact: true })).toBeDisabled()
  await page.goto(`${siteUrl}/sections/frames`)
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name, exact: true }) })
  await expect(card.getByText('active', { exact: true })).toBeVisible()
  await card.getByRole('button', { name: `Retire ${name}`, exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(card.getByText('active', { exact: true })).toBeVisible()
  await card.getByRole('button', { name: `Retire ${name}`, exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await card.getByRole('button', { name: `Retire ${name}`, exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Retire component', exact: true }).click()
  await expect(card.getByText('retired', { exact: true })).toBeVisible()
  await page.reload()
  await expect(card.getByText('retired', { exact: true })).toBeVisible()
  await card.getByRole('button', { name: `Restore ${name}`, exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Restore component', exact: true }).click()
  await expect(card.getByText('active', { exact: true })).toBeVisible()
  await card.getByRole('link', { name: `Edit component ${name}`, exact: true }).click()
  await expect(page.locator('#sec-placement')).toHaveValue('header')
  await expect(page.getByLabel('What menu holds', { exact: true })).toHaveValue('navigation')
  await page.goBack()
  await expect(card.getByText('active', { exact: true })).toBeVisible()
  await page.context().clearCookies()
  await signIn(page, 'contrib@example.test')
  const response = await page.goto(`${siteUrl}/sections/frames`)
  expect(response?.status()).toBe(404)
})
