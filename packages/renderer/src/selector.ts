// Selector scoping and validation, done with a selector parser rather than with
// string arithmetic.
//
// The rule a definition's stylesheet has to obey is simple to state — every
// selector branch must be rooted at that definition's own scope class — and it
// turns out to be impossible to check by looking at characters. CSS identifiers
// can be spelled with escapes, and an escape is not a boundary:
//
//     .cms-section--d\65 vil
//
// is the class `cms-section--devil`, so a definition with slug `d` could style
// one with slug `devil`. A prefix test sees `.cms-section--d` followed by a
// backslash, decides a backslash cannot continue an identifier, and passes it.
// Comments do the same thing (`.cms-section--d` `/**/` `evil` is one identifier
// to a browser but three tokens to a reader), and so does every-character
// escaping.
//
// postcss-selector-parser resolves those spellings the way the CSS Syntax
// specification says to, and hands back a class node whose `value` is the
// identifier — `cms-section--devil`, not the text that produced it. Comparing
// identifiers instead of substrings is the whole fix.
//
// Scope *insertion* is structural for the same reason. `selector.replace('&',
// scope)` put the scope next to characters an author chose, so `&\65 vil`
// became `.cms-section--d\65 vil`. The nesting node is now replaced with a real
// class node in the parsed tree, and the result is re-parsed and re-validated
// before it can ship — so even a serialization that happens to concatenate into
// something new is caught by the same check that catches a stored artifact.
import selectorParser from 'postcss-selector-parser'

/**
 * What a scope's identifier may contain.
 *
 * Deliberately narrower than CSS allows. Scopes are generated by this codebase
 * — `.cms-section--<slug>` and `#s<n>` — so nothing legitimate needs an escape,
 * and refusing them means no scope can be spelled two ways.
 */
const SAFE_IDENTIFIER = /^[a-zA-Z][a-zA-Z0-9_-]*$/

/** Combinators that keep the subject inside the scope. */
const DESCENDING_COMBINATORS = new Set([' ', '>', '>>'])

/** What a definition's or block's stylesheet is confined to. */
export type ScopeToken = { kind: 'class'; identifier: string } | { kind: 'id'; identifier: string }

/**
 * Read a scope from the selector string the rest of the system passes around.
 *
 * Returns null for anything that is not exactly one class or one id, which is
 * the only shape a scope is allowed to be. A scope that is a selector *list*,
 * or carries a combinator, or contains syntax, is not a scope.
 */
export function parseScopeToken(scopeSelector: string): ScopeToken | null {
  let token: ScopeToken | null = null
  let branches = 0
  try {
    selectorParser(root => {
      root.each(selector => {
        branches += 1
        const nodes = selector.nodes.filter(node => node.type !== 'comment')
        if (nodes.length !== 1) return
        const only = nodes[0]!
        // The parser is lenient about what it will call an identifier — it
        // accepted `a{` — and a scope is not a place to be lenient.
        if (!SAFE_IDENTIFIER.test(only.value ?? '')) return
        if (only.type === 'class') token = { kind: 'class', identifier: only.value }
        else if (only.type === 'id') token = { kind: 'id', identifier: only.value }
      })
    }).processSync(scopeSelector)
  } catch {
    return null
  }
  return branches === 1 ? token : null
}

/** Serialize a scope token back to selector text, escaped by the parser. */
function scopeNode(token: ScopeToken): selectorParser.ClassName | selectorParser.Identifier {
  return token.kind === 'class'
    ? selectorParser.className({ value: token.identifier })
    : selectorParser.id({ value: token.identifier })
}

/**
 * Is this branch's first compound rooted at the scope?
 *
 * The first compound is everything before the first combinator. It has to
 * contain the scope's own class or id — compared as identifiers, so spelling
 * cannot change the answer.
 */
function branchIsRooted(selector: selectorParser.Selector, token: ScopeToken): boolean {
  const compound: selectorParser.Node[] = []
  let firstCombinator: string | null = null
  for (const node of selector.nodes) {
    if (node.type === 'combinator') {
      firstCombinator = String(node.value).trim() || ' '
      break
    }
    if (node.type !== 'comment') compound.push(node)
  }
  if (compound.length === 0) return false
  // A selector's *subject* is its last compound, not its first. Rooting the
  // leftmost one confines the match only while every step descends: `~` and `+`
  // move sideways, so `.cms-section--d ~ *` selects the section's siblings —
  // everything else on the page. Only the first combinator needs checking:
  // after one descending step the subject is strictly inside the scope, and a
  // sibling of something inside is still inside.
  if (firstCombinator !== null && !DESCENDING_COMBINATORS.has(firstCombinator)) return false
  return compound.some(
    node =>
      (token.kind === 'class' && node.type === 'class' && node.value === token.identifier) ||
      (token.kind === 'id' && node.type === 'id' && node.value === token.identifier),
  )
}

/**
 * Every branch of a selector list is rooted at the scope.
 *
 * Checked per branch on purpose: `.cms-section--d .ok, body` has one branch
 * that behaves and one that restyles the page, and a whole-string test sees a
 * scope in there somewhere and says yes.
 */
export function selectorIsScoped(selector: string, scopeSelector: string): boolean {
  const token = parseScopeToken(scopeSelector)
  if (!token) return false
  let ok = true
  let branches = 0
  try {
    selectorParser(root => {
      root.each(branch => {
        branches += 1
        if (!branchIsRooted(branch, token)) ok = false
      })
    }).processSync(selector)
  } catch {
    return false
  }
  return ok && branches > 0
}

/**
 * Scope a selector list under a token, structurally.
 *
 * A branch that starts with `&` has that node replaced; anything else gets the
 * scope prepended as a descendant. Returns null when the result would not pass
 * `selectorIsScoped` — which is how `&\65 vil` is caught, since replacing the
 * nesting node produces a compound that re-parses as a different class.
 */
export function scopeSelectorList(selector: string, scopeSelector: string): string | null {
  const token = parseScopeToken(scopeSelector)
  if (!token) return null

  let out: string
  try {
    out = selectorParser(root => {
      root.each(branch => {
        const nesting = branch.nodes.findIndex(node => node.type === 'nesting')
        if (nesting >= 0) {
          branch.nodes[nesting]!.replaceWith(scopeNode(token))
          return
        }
        branch.prepend(selectorParser.combinator({ value: ' ' }))
        branch.prepend(scopeNode(token))
      })
    }).processSync(selector)
  } catch {
    return null
  }

  // Re-read what was produced. Building it structurally is not on its own a
  // guarantee about what it *means* once serialized back to text.
  return selectorIsScoped(out, scopeSelector) ? out : null
}

/** Narrow a compiled selector to known section wrappers without increasing
 * specificity or changing the original class/attribute conditions. */
export function narrowScopedSelector(
  selector: string,
  scopeSelector: string,
  indices: readonly number[],
): string | null {
  const scope = parseScopeToken(scopeSelector)
  if (
    !scope ||
    !indices.length ||
    indices.some(index => !Number.isSafeInteger(index) || index < 0) ||
    !selectorIsScoped(selector, scopeSelector)
  )
    return null
  try {
    const restriction = selectorParser().astSync(`:where(${indices.map(index => `#s${index}`).join(',')})`).nodes[0]!
      .nodes[0]!
    if (restriction.type !== 'pseudo') return null
    let valid = true
    const output = selectorParser(root =>
      root.each(branch => {
        let anchor: selectorParser.ClassName | selectorParser.Identifier | undefined
        for (const node of branch.nodes) {
          if (node.type === 'combinator') break
          if (
            ((scope.kind === 'class' && node.type === 'class') || (scope.kind === 'id' && node.type === 'id')) &&
            node.value === scope.identifier
          ) {
            anchor = node as selectorParser.ClassName | selectorParser.Identifier
            break
          }
        }
        if (!anchor) {
          valid = false
          return
        }
        branch.insertAfter(anchor, restriction.clone())
      }),
    ).processSync(selector)
    return valid && selectorIsScoped(output, scopeSelector) ? output : null
  } catch {
    return null
  }
}
